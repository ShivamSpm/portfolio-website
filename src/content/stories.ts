export const workStories = stories
  .filter((s) => s.section === "work")
  .sort((a, b) => a.order - b.order);

export const projectStories = stories
  .filter((s) => s.section === "project")
  .sort((a, b) => a.order - b.order);

/** Work stories first, then projects. "Next story" follows this order and wraps around. */
export const storyOrder = [...workStories, ...projectStories];

export function getStory(slug: string): Story | undefined {
  return stories.find((s) => s.slug === slug);
}

export function getNextStory(slug: StorySlug): Story {
  const i = storyOrder.findIndex((s) => s.slug === slug);
  return storyOrder[(i + 1) % storyOrder.length];
}

/** Steps shown on the site: those whose body is still a TODO(shivam) are hidden. */
export function visibleSteps(story: Story) {
  return story.steps.filter((step) => !step.body.includes("TODO(shivam)"));
}
